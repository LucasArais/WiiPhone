import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const base=process.env.KART_URL || 'https://localhost:8443';
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
try {
  const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1280,height:720},hasTouch:true});
  const phone=await context.newPage();
  phone.on('pageerror',e=>errors.push(e.message));
  await phone.setViewportSize({width:844,height:390});
  await phone.goto(base+'/controller.html');
  await phone.evaluate(()=>{
    window.testBeta=0;
    setInterval(()=>window.dispatchEvent(new DeviceOrientationEvent('deviceorientation',{alpha:0,beta:window.testBeta,gamma:12})),33);
  });
  await phone.click('#enable');
  await phone.waitForFunction(()=>document.getElementById('player-badge').textContent==='Jogador 1');
  const game=await context.newPage();
  game.on('pageerror',e=>errors.push(e.message));
  await game.goto(base+'/games/mario-kart/?evidence=1');
  await game.waitForFunction(()=>window.__kart?.assets);
  await game.waitForFunction(()=>document.getElementById('connection').textContent.includes('PHONE CONNECTED'));
  await phone.click('[data-button="right"]');
  await game.waitForFunction(()=>document.getElementById('chosen').textContent==='Luigi');
  await phone.click('[data-button="2"]');
  await phone.click('[data-button="2"]');
  await game.waitForFunction(()=>__kart.race.state==='racing',null,{timeout:15000});
  const cdp=await context.newCDPSession(phone);
  const gasBox=await phone.locator('[data-button="2"]').boundingBox();
  const driftBox=await phone.locator('[data-button="A"]').boundingBox();
  const gas={x:gasBox.x+gasBox.width/2,y:gasBox.y+gasBox.height/2,id:1};
  const drift={x:driftBox.x+driftBox.width/2,y:driftBox.y+driftBox.height/2,id:2};
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[gas]});
  await game.waitForFunction(()=>__kart.race.player.speed>10);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[gas,drift]});
  await phone.evaluate(()=>window.testBeta=-12);
  await game.waitForTimeout(500);
  assert.equal(await phone.locator('.held').count(),2,'multi-touch gas and drift');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
  assert.equal(await phone.locator('.held').count(),0,'release and cancellation clear buttons');
  await phone.click('#recenter');
  await game.waitForFunction(()=>__kart.paused);
  await phone.evaluate(()=>window.testBeta=0);
  await game.waitForTimeout(800);
  await phone.click('[data-button="2"]');
  await game.waitForFunction(()=>!__kart.paused);
  await mkdir(new URL('../test-results/kart/',import.meta.url),{recursive:true});
  await phone.screenshot({path:new URL('../test-results/kart/controller.png',import.meta.url).pathname});
  await phone.close();
  await game.waitForFunction(()=>__kart.paused);
  await game.keyboard.press('Enter');
  await game.waitForFunction(()=>!__kart.paused);
  assert.deepEqual(errors,[]);
  console.log('PASS: phone connected before game, driver selection, calibration, countdown, gas, multitouch, cancellation, recenter, disconnect pause and keyboard recovery. Synthetic orientation; physical phone not tested.');
} finally { await browser.close(); }
